export const themes = ['all','grecja','argentyna','transport','medycyna','zywioly','budzet'];
const pick=(items,rng)=>items[Math.min(items.length-1,Math.floor(rng()*items.length))];
export function generateAlarm({theme='all',level=1,previousBody=null}={},rng=Math.random){
  if(!themes.includes(theme)) throw new TypeError('Nieznany motyw.');
  if(!Number.isInteger(level)||level<0||level>2) throw new TypeError('Nieprawidłowy poziom dramatyzmu.');
  const pool=bodies.filter(x=>(theme==='all'||x.theme===theme)&&x.id!==previousBody);
  const body=pick(pool,rng);
  return {...body,level,text:[pick(intros[level],rng),body.text,pick(endings[level],rng)].join(' ')};
}
